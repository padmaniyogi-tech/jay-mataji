"use client";

import { useCallback, useEffect, useRef, useState } from "react";
import { RotateCcw, ShieldAlert, ShieldX, Sparkles } from "lucide-react";
import { Alert, Badge, Card, CardBody, CardHeader, Progress, StatCard } from "@/components/ui/primitives";
import { Button } from "@/components/ui/button";
import { Field, Input } from "@/components/ui/field";
import { formatCount, formatUtcTime } from "@/lib/demo/format";

/** Mirrors DemoSnapshot in src/lib/demo/service.ts. Statuses are simulation-only vocabulary. */
type DemoRun = {
  publicId: string;
  status: "simulating" | "simulation_complete";
  handle: string;
  profileUrl: string;
  requestedQuantity: number;
  simulatedDelivered: number;
  remaining: number;
  percent: number;
  elapsedSeconds: number;
  durationSeconds: number;
  startedAt: string;
  completedAt: string | null;
  simulated: true;
  notice: string;
  realFollowersDelivered: 0;
  deliveryStatus: "not_delivered";
  deliveryMessage: string;
};

type Limits = { min: number; max: number; step: number; durationSeconds: number };

const STAGES = [
  { at: 0, label: "Demo run accepted", detail: "A simulated run was created. No Instagram account was contacted." },
  { at: 20, label: "Simulated audience match", detail: "The simulator fabricates an audience — nothing is sent to Instagram." },
  { at: 55, label: "Simulated progress", detail: "Counters are generated by a timer in this app, not measured from Instagram." },
  { at: 100, label: "Simulation finished", detail: "The simulator stopped. Real followers added to the account: 0." },
];

export function DemoRunner({
  limits,
  realDeliveryAvailable,
  realDeliveryMessage,
  realDeliveryAlternative,
}: {
  limits: Limits;
  realDeliveryAvailable: boolean;
  realDeliveryMessage: string;
  realDeliveryAlternative: string;
}) {
  const [target, setTarget] = useState("");
  const [quantity, setQuantity] = useState(String(Math.min(1000, limits.max)));
  const [run, setRun] = useState<DemoRun | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [fieldError, setFieldError] = useState<Record<string, string>>({});
  const [starting, setStarting] = useState(false);
  const pollRef = useRef<ReturnType<typeof setInterval> | null>(null);

  const stopPolling = useCallback(() => {
    if (pollRef.current) {
      clearInterval(pollRef.current);
      pollRef.current = null;
    }
  }, []);

  useEffect(() => stopPolling, [stopPolling]);

  const poll = useCallback(
    async (publicId: string) => {
      try {
        const res = await fetch(`/api/demo/runs/${publicId}`, { cache: "no-store" });
        if (!res.ok) return;
        const json = (await res.json()) as { data?: { run?: DemoRun } };
        if (json.data?.run) {
          setRun(json.data.run);
          if (json.data.run.status === "simulation_complete") stopPolling();
        }
      } catch {
        // Transient network hiccup: the next tick retries.
      }
    },
    [stopPolling],
  );

  async function startDemo(event: React.FormEvent) {
    event.preventDefault();
    setError(null);
    setFieldError({});
    setStarting(true);
    stopPolling();
    setRun(null);
    try {
      const res = await fetch("/api/demo/runs", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ target, quantity: Number(quantity) }),
      });
      const json = (await res.json().catch(() => ({}))) as {
        ok?: boolean;
        data?: { run?: DemoRun };
        error?: { message?: string; details?: Array<{ path: string; message: string }> };
      };

      if (!res.ok || !json.data?.run) {
        setError(json.error?.message ?? "Could not start the demo. Please check the username and try again.");
        const fields: Record<string, string> = {};
        for (const issue of json.error?.details ?? []) fields[issue.path ?? ""] = issue.message;
        setFieldError(fields);
        return;
      }

      const started = json.data.run;
      setRun(started);
      pollRef.current = setInterval(() => void poll(started.publicId), 1500);
    } catch {
      setError("Network error. Please try again.");
    } finally {
      setStarting(false);
    }
  }

  function reset() {
    stopPolling();
    setRun(null);
    setError(null);
    setFieldError({});
    setTarget("");
  }

  const finished = run?.status === "simulation_complete";

  return (
    <div className="space-y-6">
      <Alert tone="demo" title="Demo simulation only — no real Instagram followers are delivered.">
        This demo runs a timer inside Amplifi to show the campaign workflow. It does not contact Instagram, does not use
        bots or fake accounts, and never asks for an Instagram password, cookie or token. Results shown here are
        simulated.
      </Alert>

      {!run && (
        <Card>
          <CardHeader
            title="Test Instagram Followers"
            description="Enter a public username and a quantity. No login, no payment, no email."
          />
          <CardBody>
            <form onSubmit={startDemo} className="space-y-5" noValidate>
              <Field
                label="Instagram username or public profile URL"
                htmlFor="demo-target"
                required
                error={fieldError.target}
                hint="For example: @yourbrand or https://www.instagram.com/yourbrand/"
              >
                <Input
                  id="demo-target"
                  name="target"
                  autoComplete="off"
                  spellCheck={false}
                  placeholder="@yourbrand"
                  value={target}
                  onChange={(e) => setTarget(e.target.value)}
                  required
                />
              </Field>

              <Field
                label="Number of followers to test"
                htmlFor="demo-quantity"
                required
                error={fieldError.quantity}
                hint={`Demo range: ${formatCount(limits.min)}–${formatCount(limits.max)}, in steps of ${formatCount(limits.step)}.`}
              >
                <Input
                  id="demo-quantity"
                  name="quantity"
                  type="number"
                  inputMode="numeric"
                  min={limits.min}
                  max={limits.max}
                  step={limits.step}
                  value={quantity}
                  onChange={(e) => setQuantity(e.target.value)}
                  required
                />
              </Field>

              <div className="flex flex-wrap gap-2" aria-label="Quick quantities">
                {[500, 1000, 2500, limits.max].map((value) => (
                  <button
                    key={value}
                    type="button"
                    onClick={() => setQuantity(String(value))}
                    className="rounded-full border border-line px-3 py-1.5 text-xs font-medium text-ink-soft transition hover:border-brand-300 hover:text-brand-700"
                  >
                    {formatCount(value)}
                  </button>
                ))}
              </div>

              {error && <Alert tone="danger">{error}</Alert>}

              <div className="flex flex-col gap-3 sm:flex-row sm:items-center">
                <Button type="submit" loading={starting} className="w-full sm:w-auto">
                  <Sparkles aria-hidden className="mr-2 h-4 w-4" />
                  Start Demo
                </Button>
                <p className="text-xs text-ink-soft">Takes about {limits.durationSeconds} seconds to finish.</p>
              </div>
            </form>
          </CardBody>
        </Card>
      )}

      {run && (
        <Card>
          <CardHeader
            title={finished ? "Demo result — simulated" : "Demo running — simulated"}
            description={`Reference ${run.publicId} · started ${formatUtcTime(run.startedAt)}`}
            action={
              <Badge tone={finished ? "demo" : "progress"}>
                {finished ? "SIMULATION COMPLETE · NOT A DELIVERY" : "SIMULATING"}
              </Badge>
            }
          />

          <CardBody className="space-y-6">
            <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
              <StatCard label="Username" value={`@${run.handle}`} hint="Entered by you" />
              <StatCard
                label="Requested"
                value={formatCount(run.requestedQuantity)}
                hint="Simulated followers"
              />
              <StatCard
                label="Simulated count"
                value={formatCount(finished ? run.requestedQuantity : run.simulatedDelivered)}
                hint={finished ? "Produced by the timer (not real)" : "Counting up (not real)"}
              />
              <StatCard
                label="Real followers added"
                value="0"
                hint="None — this is not a delivery"
                tone="demo"
              />
            </div>

            <Progress
              value={finished ? 100 : run.percent}
              label={finished ? "Simulation finished (0 real followers)" : `Simulation progress ${run.percent}%`}
              demo
            />

            <div>
              <div className="mb-2 flex items-center justify-between text-sm">
                <span className="font-medium text-ink">Demo status</span>
                <span className="font-mono text-xs uppercase tracking-wide text-ink-soft">{run.status}</span>
              </div>
              <ol className="space-y-3">
                {STAGES.map((stage) => {
                  const reached = run.percent >= stage.at;
                  return (
                    <li key={stage.label} className="flex gap-3">
                      <span
                        aria-hidden
                        className={`mt-1 h-2.5 w-2.5 shrink-0 rounded-full ${reached ? "bg-brand-500" : "bg-line"}`}
                      />
                      <div>
                        <p className={`text-sm font-medium ${reached ? "text-ink" : "text-ink-faint"}`}>{stage.label}</p>
                        <p className="text-xs leading-relaxed text-ink-soft">{stage.detail}</p>
                      </div>
                    </li>
                  );
                })}
              </ol>
            </div>

            {!finished && (
              <p className="text-xs text-ink-soft" aria-live="polite">
                Elapsed {run.elapsedSeconds}s of {run.durationSeconds}s · {formatCount(run.remaining)} simulated
                followers remaining · real followers added: 0
              </p>
            )}

            {finished && (
              <div className="space-y-4">
                <Alert tone="warn" title="Simulation finished — no followers were delivered">
                  The simulator counted {formatCount(run.requestedQuantity)} for{" "}
                  <span className="font-mono">@{run.handle}</span>. Nothing was sent to Instagram, so{" "}
                  <strong>{formatCount(run.realFollowersDelivered)} real followers were added</strong> and the account
                  is unchanged. Verify it yourself:{" "}
                  <a
                    href={run.profileUrl}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="font-medium underline decoration-dotted"
                  >
                    open @{run.handle} on Instagram
                  </a>
                  .
                </Alert>

                <div className="rounded-xl border border-line bg-canvas p-4">
                  <p className="text-sm font-medium text-ink">Recorded as</p>
                  <p className="mt-1 text-xs leading-relaxed text-ink-soft">
                    {run.deliveryMessage} Delivery status:{" "}
                    <span className="font-mono uppercase">{run.deliveryStatus.replace(/_/g, " ")}</span>.
                  </p>
                </div>

                <div className="rounded-xl border border-accent-300 bg-accent-50 p-4">
                  <div className="flex items-center justify-between gap-2">
                    <p className="text-sm font-medium text-accent-900">Real delivery</p>
                    <span className="rounded-full border border-accent-300 bg-white/70 px-2 py-0.5 text-[10px] font-semibold uppercase tracking-wide text-accent-900">
                      {realDeliveryAvailable ? "provider configured" : "not configured"}
                    </span>
                  </div>
                  <p className="mt-1 text-xs leading-relaxed text-accent-900">{realDeliveryMessage}</p>
                  <p className="mt-2 text-xs leading-relaxed text-accent-900">{realDeliveryAlternative}</p>
                </div>

                <Button type="button" variant="secondary" onClick={reset}>
                  <RotateCcw aria-hidden className="mr-2 h-4 w-4" />
                  Run another demo
                </Button>
              </div>
            )}

            {!finished && (
              <Button type="button" variant="ghost" onClick={reset}>
                Cancel and start over
              </Button>
            )}

            <p className="flex items-start gap-2 text-xs text-ink-soft">
              <ShieldX aria-hidden className="mt-0.5 h-4 w-4 shrink-0" />
              Demo runs are stored separately from customer orders: no payment, no invoice, no delivery record. They
              never appear in revenue or delivery reporting.
            </p>
          </CardBody>
        </Card>
      )}

      {run && !finished && (
        <p className="flex items-start gap-2 text-xs text-ink-soft">
          <ShieldAlert aria-hidden className="mt-0.5 h-4 w-4 shrink-0" />
          Please keep this tab open while the simulation runs.
        </p>
      )}
    </div>
  );
}
